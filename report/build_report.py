# 본문 문단 생성. boldlead=True이고 두 칸 공백이 있으면 그 앞부분만 강조한다.
def p(text, boldlead=False):
    x = D.add_paragraph()
    if boldlead and "  " in text:
        a, b = text.split("  ", 1)
        x.add_run(a + "  ").bold = True
        x.add_run(b)
    else:
        x.add_run(text)
    return x


# Word의 제목 스타일을 사용해 제목 계층을 유지한다. level=0은 표지 제목이다.
def h(text, level=2):
    return D.add_heading(text, level)


# 장을 새 페이지에서 시작하고 1단계 제목을 붙인다.
def page(title):
    D.add_page_break()
    h(title, 1)


# 출처·보조 설명용 문단. 본문보다 작은 글자와 옅은 색을 적용한다.
def small(text):
    x = p(text)
    for r in x.runs:
        r.font.size = Pt(9.5)
        r.font.color.rgb = RGBColor.from_string("52666A")
    return x


# 비교 표를 만들고 열 너비·셀 여백·머리글을 일관되게 지정한다.
# 행이 페이지 경계에서 나뉘지 않게 하고 다음 페이지에서도 머리글을 반복한다.
# OOXML 속성을 직접 넣는 부분은 python-docx의 고수준 API에 없는 서식 처리를 위한 것이다.
def table(headers, rows, widths=None):
    t = D.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    if widths:
        for col, width in zip(t.columns, widths):
            col.width = Inches(width)
    for c, text in zip(t.rows[0].cells, headers):
        c.text = text
    for values in rows:
        for c, text in zip(t.add_row().cells, values):
            c.text = str(text)
    for i, row in enumerate(t.rows):
        trpr = row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        trpr.append(cant)
        if i == 0:
            repeat = OxmlElement("w:tblHeader")
            trpr.append(repeat)
        for j, c in enumerate(row.cells):
            if widths:
                c.width = Inches(widths[j])
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr = c._tc.get_or_add_tcPr()
            m = OxmlElement("w:tcMar")
            for edge in ["top", "left", "bottom", "right"]:
                v = OxmlElement("w:" + edge)
                v.set(qn("w:w"), "100")
                v.set(qn("w:type"), "dxa")
                m.append(v)
            pr.append(m)
            if i == 0:
                sh = OxmlElement("w:shd")
                sh.set(qn("w:fill"), "E7EFEC")
                pr.append(sh)
            for para in c.paragraphs:
                para.paragraph_format.space_after = Pt(3)
                para.paragraph_format.space_before = Pt(3)
                para.paragraph_format.line_spacing = Pt(14.5)
                for run in para.runs:
                    run.font.size = Pt(10.3)
                    run.bold = i == 0
    D.add_paragraph().paragraph_format.space_after = Pt(1)
    return t


